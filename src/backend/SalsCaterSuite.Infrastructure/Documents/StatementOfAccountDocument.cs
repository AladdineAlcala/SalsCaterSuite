using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using SalsCaterSuite.Application.Features.Customers.DTOs.Request;
using SalsCaterSuite.Application.Features.Customers.DTOs.Response;

namespace SalsCaterSuite.Infrastructure.Documents;

public class StatementOfAccountDocument : IDocument
{
    public CustomerStatementResponse Statement { get; }

    public StatementOfAccountDocument(CustomerStatementResponse statement)
    {
        Statement = statement;
    }

    public DocumentMetadata GetMetadata() => DocumentMetadata.Default;
    public DocumentSettings GetSettings() => DocumentSettings.Default;

    public void Compose(IDocumentContainer container)
    {
        container.Page(page =>
        {
            page.Size(PageSizes.A4);
            page.Margin(1.5f, Unit.Centimetre);
            page.DefaultTextStyle(x => x.FontSize(10).FontFamily("Arial"));

            page.Header().Column(col =>
            {
                col.Item().Text("SAL'S CATERING SERVICES").Bold().FontSize(16).FontColor(Colors.Blue.Darken3);
                col.Item().Text("STATEMENT OF ACCOUNT / RECEIVABLES").Bold().FontSize(12);
                col.Item().LineHorizontal(1).LineColor(Colors.Grey.Lighten1);
            });

            page.Content().PaddingVertical(10).Column(col =>
            {
                col.Item().Row(r =>
                {
                    r.RelativeItem().Column(c =>
                    {
                        c.Item().Text($"Customer: {Statement.CustomerName}").Bold();
                        c.Item().Text($"Contact: {Statement.Contact ?? "N/A"}");
                        c.Item().Text($"Address: {Statement.Address ?? "N/A"}");
                    });
                    r.RelativeItem().AlignRight().Column(c =>
                    {
                        c.Item().Text($"Statement Date: {DateTime.Now:yyyy-MM-dd}").Bold();
                        c.Item().Text($"Total Outstanding: PHP {Statement.OutstandingBalance:N2}").Bold().FontColor(Colors.Red.Darken2);
                    });
                });

                col.Item().PaddingTop(15).Table(table =>
                {
                    table.ColumnsDefinition(cols =>
                    {
                        cols.ConstantColumn(60);
                        cols.ConstantColumn(80);
                        cols.RelativeColumn(3);
                        cols.RelativeColumn(2);
                        cols.RelativeColumn(2);
                        cols.RelativeColumn(2);
                    });

                    table.Header(h =>
                    {
                        h.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text("TRN #").Bold();
                        h.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text("Event Date").Bold();
                        h.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text("Occasion").Bold();
                        h.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text("Billed (PHP)").Bold();
                        h.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text("Paid (PHP)").Bold();
                        h.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text("Balance (PHP)").Bold();
                    });

                    foreach (var item in Statement.Transactions)
                    {
                        table.Cell().Padding(5).Text($"#{item.TransactionId}");
                        table.Cell().Padding(5).Text($"{item.EventDate:yyyy-MM-dd}");
                        table.Cell().Padding(5).Text(item.Occasion);
                        table.Cell().Padding(5).Text($"{item.Amount:N2}");
                        table.Cell().Padding(5).Text($"{item.Paid:N2}");
                        table.Cell().Padding(5).Text($"{item.Balance:N2}").Bold();
                    }
                });

                col.Item().PaddingTop(20).AlignRight().Column(c =>
                {
                    c.Item().Text($"Total Billed: PHP {Statement.TotalBilled:N2}");
                    c.Item().Text($"Total Payments: PHP {Statement.TotalPaid:N2}").FontColor(Colors.Green.Darken2);
                    c.Item().Text($"Total Due: PHP {Statement.OutstandingBalance:N2}").Bold().FontSize(12).FontColor(Colors.Red.Darken2);
                });
            });

            page.Footer().AlignCenter().Text(x =>
            {
                x.Span("Generated by Sal's CaterSuite | Page ");
                x.CurrentPageNumber();
                x.Span(" of ");
                x.TotalPages();
            });
        });
    }
}

