using QuestPDF.Fluent;
using QuestPDF.Helpers;
using QuestPDF.Infrastructure;
using SalsCaterSuite.Application.Features.Bookings.DTOs;

namespace SalsCaterSuite.Infrastructure.Documents;

public class ContractDocument : IDocument
{
    public BookingDto Booking { get; }

    public ContractDocument(BookingDto booking)
    {
        Booking = booking;
    }

    public DocumentMetadata GetMetadata() => DocumentMetadata.Default;
    public DocumentSettings GetSettings() => DocumentSettings.Default;

    public void Compose(IDocumentContainer container)
    {
        container.Page(page =>
        {
            page.Size(PageSizes.A4);
            page.Margin(1.5f, Unit.Centimetre);
            page.DefaultTextStyle(x => x.FontSize(10).FontFamily("Arial"));

            page.Header().Column(col =>
            {
                col.Item().Text("SAL'S CATERING SERVICES & EVENT SUITE")
                    .Bold().FontSize(16).FontColor(Colors.Blue.Darken3);
                col.Item().Text("CATERING CONTRACT & SERVICE AGREEMENT")
                    .Bold().FontSize(12).FontColor(Colors.Grey.Darken2);
                col.Item().LineHorizontal(1).LineColor(Colors.Grey.Lighten1);
            });

            page.Content().PaddingVertical(10).Column(col =>
            {
                col.Item().Row(row =>
                {
                    row.RelativeItem().Column(c =>
                    {
                        c.Item().Text($"Contract Ref: {Booking.Reference ?? $"TRN-{Booking.TransactionId:D5}"}").Bold();
                        c.Item().Text($"Client Name: {Booking.CustomerName}");
                        c.Item().Text($"Contact No: {Booking.CustomerContact ?? "N/A"}");
                    });
                    row.RelativeItem().Column(c =>
                    {
                        c.Item().Text($"Event Date: {Booking.EventDate:MMMM dd, yyyy}").Bold();
                        c.Item().Text($"Occasion: {Booking.Occasion}");
                        c.Item().Text($"Venue: {Booking.Venue}");
                    });
                });

                col.Item().PaddingTop(15).Table(table =>
                {
                    table.ColumnsDefinition(columns =>
                    {
                        columns.RelativeColumn(3);
                        columns.RelativeColumn(1);
                        columns.RelativeColumn(2);
                        columns.RelativeColumn(2);
                    });

                    table.Header(header =>
                    {
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text("Service Details").Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text("Pax").Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text("Rate/Pax").Bold();
                        header.Cell().Background(Colors.Grey.Lighten3).Padding(5).Text("Total (PHP)").Bold();
                    });

                    table.Cell().Padding(5).Text(Booking.PackageName ?? "Catering Buffet Package");
                    table.Cell().Padding(5).Text($"{Booking.NumberOfHeads}");
                    table.Cell().Padding(5).Text($"PHP {((Booking.PackageAmount) / (Booking.NumberOfHeads > 0 ? Booking.NumberOfHeads : 1)):N2}");
                    table.Cell().Padding(5).Text($"PHP {(Booking.PackageAmount):N2}");
                });

                col.Item().PaddingTop(20).AlignRight().Column(c =>
                {
                    c.Item().Text($"Total Package Amount: PHP {(Booking.PackageAmount):N2}").Bold();
                    c.Item().Text($"Total Payments Received: PHP {Booking.AmountPaid:N2}").FontColor(Colors.Green.Darken2);
                    c.Item().Text($"Remaining Balance: PHP {Booking.Balance:N2}").Bold().FontColor(Colors.Red.Darken2);
                });

                col.Item().PaddingTop(30).Row(row =>
                {
                    row.RelativeItem().Column(c =>
                    {
                        c.Item().Text("Client Signature over Printed Name:");
                        c.Item().PaddingTop(35).LineHorizontal(1);
                        c.Item().PaddingTop(2).Text(Booking.CustomerName ?? "Client").SemiBold();
                    });
                    row.ConstantItem(40);
                    row.RelativeItem().Column(c =>
                    {
                        c.Item().Text("Sal's Catering Authorized Representative:");
                        c.Item().PaddingTop(35).LineHorizontal(1);
                        c.Item().PaddingTop(2).Text("Authorized Caterer Representative").SemiBold();
                    });
                });
            });

            page.Footer().AlignCenter().Text(x =>
            {
                x.Span("Generated by Sal's CaterSuite | Page ");
                x.CurrentPageNumber();
                x.Span(" of ");
                x.TotalPages();
            });
        });
    }
}

