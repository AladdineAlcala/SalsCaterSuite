using SalsCaterSuite.Domain.Common;

namespace SalsCaterSuite.Domain.Entities;

/// <summary>
/// The read-only applicable-pax classification of a catering package tier
/// (REQ-PKG-04, DEC-173).
/// <para>
/// This is <b>fixed reference data</b>: the five rows are seeded by the schema migration with
/// their stated identifiers and labels, and the table exposes no create, update or delete
/// surface. The identifiers are therefore <b>not</b> database-generated — they are part of the
/// reference data itself.
/// </para>
/// <para>
/// The label is <b>descriptive classification only</b>. It is stored and published verbatim and
/// is never parsed as a numeric interval; it does not constrain <c>PackageType</c>, does not
/// replace or validate <c>Package.MinPax</c>, and has no effect on booking headcount
/// eligibility, quoting or pricing. Option 5 ("Not Applicable to PackMeals") is deliberately
/// <b>not</b> coupled to <c>PackageType.Pm</c>.
/// </para>
/// <para>
/// The entity inherits <see cref="BaseEntity"/> and therefore carries the standard DEC-038
/// audit columns, exactly like every other entity in the model.
/// </para>
/// </summary>
public class PackagePaxApplicable : BaseEntity
{
    /// <summary>
    /// The fixed identifier of the classification. It is part of the reference data and is never
    /// generated by the database.
    /// </summary>
    public int NumPaxId { get; set; }

    /// <summary>
    /// The display label of the classification, stored and published verbatim.
    /// </summary>
    public string PackageApplicablePax { get; set; } = string.Empty;
}
